/** `#0F766E` -> `Color(0xFF0F766E)`, `rgba(20,32,27,0.48)` -> `Color.fromRGBO(20, 32, 27, 0.48)`. */
export function dartColor(value: string): string {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex?.[1]) return `Color(0xFF${hex[1].toUpperCase()})`;
  const rgba = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/.exec(value);
  if (rgba) return `Color.fromRGBO(${rgba[1]}, ${rgba[2]}, ${rgba[3]}, ${rgba[4]})`;
  throw new Error(`Unsupported colour "${value}"`);
}

const num = (n: number) => (Number.isInteger(n) ? `${n}.0` : `${n}`);
const str = (s: string) => `'${s.replace(/'/g, "\\'")}'`;

function colorsInstance(tokens: Tokens, mode: Mode): string {
  const fields = entries(tokens.color[mode]).map(([k, v]) => `    ${k}: ${dartColor(v)},`);
  return `  static const ${mode} = AppColors(\n${fields.join('\n')}\n  );`;
}

export function buildDart(tokens: Tokens): string {
  const colorNames = entries(tokens.color.light).map(([k]) => k);
  const f = tokens.font;
  const weightName: Record<number, string> = { 400: 'w400', 500: 'w500', 600: 'w600', 700: 'w700' };

  const out: string[] = [
    '// GENERATED by `pnpm tokens:gen` from design/tokens.json. Do not edit.',
    '// ignore_for_file: lines_longer_than_80_chars',
    "import 'package:flutter/material.dart';",
    '',
    'class AppColors {',
    '  const AppColors({',
    ...colorNames.map((k) => `    required this.${k},`),
    '  });',
    '',
    ...colorNames.map((k) => `  final Color ${k};`),
    '',
    colorsInstance(tokens, 'light'),
    '',
    colorsInstance(tokens, 'dark'),
    '',
    '  static AppColors lerp(AppColors a, AppColors b, double t) => AppColors(',
    ...colorNames.map((k) => `    ${k}: Color.lerp(a.${k}, b.${k}, t)!,`),
    '  );',
    '}',
    '',
    '/// Answer option tile colours for one state.',
    'class AppOptionStyle {',
    '  const AppOptionStyle({required this.bg, required this.border, required this.badgeBg, required this.badgeText});',
    '',
    '  final Color bg;',
    '  final Color border;',
    '  final Color badgeBg;',
    '  final Color badgeText;',
    '}',
    '',
    `enum OptionState { ${OPTION_STATES.join(', ')} }`,
    '',
    'abstract final class AppSpace {',
    ...entries(tokens.space).map(([k, v]) => `  static const double s${k} = ${num(v)};`),
    '}',
    '',
    'abstract final class AppRadius {',
    ...entries(tokens.radius).map(([k, v]) => `  static const double ${k} = ${num(v)};`),
    '}',
    '',
    'abstract final class AppBorder {',
    ...entries(tokens.border).map(([k, v]) => `  static const double ${k} = ${num(v)};`),
    '}',
    '',
    'abstract final class AppSize {',
    ...entries(tokens.size).map(([k, v]) => `  static const double ${k} = ${num(v)};`),
    '}',
    '',
    'abstract final class AppBreakpoint {',
    ...entries(tokens.breakpoint).map(([k, v]) => `  static const double ${k} = ${num(v)};`),
    '}',
    '',
    'abstract final class AppMotion {',
    ...entries(tokens.motion.duration).map(
      ([k, v]) => `  static const Duration ${k} = Duration(milliseconds: ${v});`,
    ),
    '}',
    '',
    'abstract final class AppText {',
    `  static const String fontBangla = ${str(f.family.bangla)};`,
    `  static const String fontLatin = ${str(f.family.latin)};`,
    `  static const String fontMono = ${str(f.family.mono)};`,
    `  static const String fontDisplay = ${str(f.family.display)};`,
    `  static const List<String> fontFallback = [${f.family.flutterFallback.map(str).join(', ')}];`,
    '',
    ...entries(f.size).map(([k, v]) => `  static const double ${k} = ${num(v)};`),
    '',
    ...entries(f.lineHeight).map(
      ([k, v]) =>
        `  static const double lineHeight${k[0]!.toUpperCase()}${k.slice(1)} = ${num(v)};`,
    ),
    '',
    ...entries(f.weight).map(
      ([k, v]) => `  static const FontWeight ${k} = FontWeight.${weightName[v] ?? 'w400'};`,
    ),
    '}',
    '',
    '/// Token access from widgets: `Theme.of(context).extension<AppTokens>()!`.',
    'class AppTokens extends ThemeExtension<AppTokens> {',
    '  const AppTokens({required this.colors});',
    '',
    '  final AppColors colors;',
    '',
    '  static const light = AppTokens(colors: AppColors.light);',
    '  static const dark = AppTokens(colors: AppColors.dark);',
    '',
    '  AppOptionStyle option(OptionState state) {',
    '    final c = colors;',
    '    switch (state) {',
    ...OPTION_STATES.flatMap((s) => {
      const o = tokens.option[s];
      return [
        `      case OptionState.${s}:`,
        `        return AppOptionStyle(bg: c.${o.bg}, border: c.${o.border}, badgeBg: c.${o.badgeBg}, badgeText: c.${o.badgeText});`,
      ];
    }),
    '    }',
    '  }',
    '',
    '  @override',
    '  AppTokens copyWith({AppColors? colors}) => AppTokens(colors: colors ?? this.colors);',
    '',
    '  @override',
    '  AppTokens lerp(covariant ThemeExtension<AppTokens>? other, double t) {',
    '    if (other is! AppTokens) return this;',
    '    return AppTokens(colors: AppColors.lerp(colors, other.colors, t));',
    '  }',
    '}',
    '',
    'TextStyle _style(double size, FontWeight weight, double height, Color color) => TextStyle(',
    '  fontFamily: AppText.fontLatin,',
    '  fontFamilyFallback: AppText.fontFallback,',
    '  fontSize: size,',
    '  fontWeight: weight,',
    '  height: height,',
    '  color: color,',
    ');',
    '',
    '/// Material 3 theme built from the tokens.',
    'ThemeData buildTheme(Brightness brightness) {',
    '  final isDark = brightness == Brightness.dark;',
    '  final c = isDark ? AppColors.dark : AppColors.light;',
    '  final scheme = ColorScheme(',
    '    brightness: brightness,',
    '    primary: c.primary,',
    '    onPrimary: c.onPrimary,',
    '    primaryContainer: c.primarySoft,',
    '    onPrimaryContainer: c.text,',
    '    secondary: c.accent,',
    '    onSecondary: c.onAccent,',
    '    secondaryContainer: c.accentSoft,',
    '    onSecondaryContainer: c.text,',
    '    tertiary: c.live,',
    '    onTertiary: c.onPrimary,',
    '    error: c.danger,',
    '    onError: c.onPrimary,',
    '    errorContainer: c.dangerSoft,',
    '    onErrorContainer: c.danger,',
    '    surface: c.surface,',
    '    onSurface: c.text,',
    '    onSurfaceVariant: c.textMuted,',
    '    surfaceContainerLowest: c.bg,',
    '    surfaceContainerLow: c.surface,',
    '    surfaceContainer: c.surfaceMuted,',
    '    surfaceContainerHigh: c.surfaceMuted,',
    '    surfaceContainerHighest: c.surfaceSunken,',
    '    outline: c.borderStrong,',
    '    outlineVariant: c.border,',
    '    scrim: c.overlay,',
    '  );',
    '  final textTheme = TextTheme(',
    '    displaySmall: _style(AppText.display, AppText.bold, AppText.lineHeightTight, c.text),',
    '    headlineMedium: _style(AppText.h1, AppText.bold, AppText.lineHeightTight, c.text),',
    '    headlineSmall: _style(AppText.h2, AppText.semibold, AppText.lineHeightTight, c.text),',
    '    titleMedium: _style(AppText.h3, AppText.semibold, AppText.lineHeightNormal, c.text),',
    '    bodyLarge: _style(AppText.body, AppText.regular, AppText.lineHeightNormal, c.text),',
    '    bodyMedium: _style(AppText.bodySm, AppText.regular, AppText.lineHeightNormal, c.textMuted),',
    '    labelMedium: _style(AppText.caption, AppText.medium, AppText.lineHeightNormal, c.textMuted),',
    '    labelSmall: _style(AppText.overline, AppText.medium, AppText.lineHeightNormal, c.textMuted),',
    '  );',
    '  return ThemeData(',
    '    useMaterial3: true,',
    '    brightness: brightness,',
    '    colorScheme: scheme,',
    '    scaffoldBackgroundColor: c.bg,',
    '    fontFamily: AppText.fontLatin,',
    '    fontFamilyFallback: AppText.fontFallback,',
    '    textTheme: textTheme,',
    '    dividerColor: c.border,',
    '    extensions: [isDark ? AppTokens.dark : AppTokens.light],',
    '  );',
    '}',
    '',
  ];
  return out.join('\n');
}
