import type { Mode, Tokens } from './tokens';
import { OPTION_STATES, entries, kebab } from './tokens';

export const HEADER = '/* Generated by `pnpm tokens:gen` from design/tokens.json. Do not edit. */';

function colorVars(tokens: Tokens, mode: Mode, indent: string): string[] {
  const c = tokens.color[mode];
  const lines = entries(c).map(([name, value]) => `${indent}--mcq-color-${kebab(name)}: ${value};`);
  for (const state of OPTION_STATES) {
    for (const [part, ref] of entries({ ...tokens.option[state] })) {
      lines.push(`${indent}--mcq-option-${state}-${kebab(part)}: var(--mcq-color-${kebab(ref)});`);
    }
  }
  return lines;
}

function staticVars(tokens: Tokens): string[] {
  const px = (n: number) => (n === 0 ? '0' : `${n}px`);
  const f = tokens.font;
  return [
    `  --mcq-font-bangla: '${f.family.bangla}';`,
    `  --mcq-font-latin: '${f.family.latin}';`,
    `  --mcq-font-mono: '${f.family.mono}', ui-monospace, monospace;`,
    `  --mcq-font-sans: ${f.family.stackWeb};`,
    ...entries(f.weight).map(([k, v]) => `  --mcq-font-weight-${kebab(k)}: ${v};`),
    ...entries(f.size).map(([k, v]) => `  --mcq-font-size-${kebab(k)}: ${px(v)};`),
    ...entries(f.lineHeight).map(([k, v]) => `  --mcq-line-height-${kebab(k)}: ${v};`),
    ...entries(tokens.space).map(([k, v]) => `  --mcq-space-${k}: ${px(v)};`),
    ...entries(tokens.radius).map(([k, v]) => `  --mcq-radius-${kebab(k)}: ${px(v)};`),
    ...entries(tokens.border).map(([k, v]) => `  --mcq-border-${kebab(k)}: ${px(v)};`),
    ...entries(tokens.shadow).map(([k, v]) => `  --mcq-shadow-${kebab(k)}: ${v};`),
    ...entries(tokens.motion.duration).map(([k, v]) => `  --mcq-duration-${kebab(k)}: ${v}ms;`),
    ...entries(tokens.motion.easing).map(([k, v]) => `  --mcq-easing-${kebab(k)}: ${v};`),
    ...entries(tokens.size).map(([k, v]) => `  --mcq-size-${kebab(k)}: ${px(v)};`),
    ...entries(tokens.breakpoint).map(([k, v]) => `  --mcq-breakpoint-${kebab(k)}: ${px(v)};`),
    ...entries(tokens.zIndex).map(([k, v]) => `  --mcq-z-${kebab(k)}: ${v};`),
  ];
}

/**
 * CSS variables. Light is the default; dark applies with `data-theme="dark"` on <html>, or with
 * the OS setting unless the page forces `data-theme="light"`.
 */
export function buildCss(tokens: Tokens): string {
  const dark = colorVars(tokens, 'dark', '    ');
  return [
    HEADER,
    ':root {',
    '  color-scheme: light;',
    ...staticVars(tokens),
    ...colorVars(tokens, 'light', '  '),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    '    color-scheme: dark;',
    ...dark,
    '  }',
    '}',
    '',
    ':root[data-theme="dark"] {',
    '  color-scheme: dark;',
    ...dark.map((l) => l.slice(2)),
    '}',
    '',
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...entries(tokens.motion.duration).map(([k]) => `    --mcq-duration-${kebab(k)}: 0ms;`),
    '  }',
    '}',
    '',
  ].join('\n');
}

/**
 * Tailwind v4 theme. Default palettes, sizes and radii are reset so only token utilities exist
 * (`bg-surface`, `text-text-muted`, `rounded-md`, `text-question`, `p-4` = 16px, ...).
 */
export function buildTailwindTheme(tokens: Tokens): string {
  const lines: string[] = [HEADER, '@theme inline {'];
  const add = (l: string) => lines.push(`  ${l}`);

  add('--color-*: initial;');
  add('--color-transparent: transparent;');
  add('--color-current: currentColor;');
  for (const [name] of entries(tokens.color.light)) {
    add(`--color-${kebab(name)}: var(--mcq-color-${kebab(name)});`);
  }

  add('--font-*: initial;');
  add('--font-sans: var(--mcq-font-sans);');
  add('--font-bangla: var(--mcq-font-bangla), var(--mcq-font-sans);');
  add('--font-mono: var(--mcq-font-mono);');
  for (const [k] of entries(tokens.font.weight)) {
    add(`--font-weight-${kebab(k)}: var(--mcq-font-weight-${kebab(k)});`);
  }

  // Line height per size, from docs/05-DESIGN-SYSTEM.md section 3.
  const lineHeightFor: Record<string, string> = {
    display: 'tight',
    h1: 'tight',
    h2: 'tight',
    h3: 'normal',
    question: 'relaxed',
    option: 'relaxed',
    timer: 'tight',
    stat: 'tight',
  };
  add('--text-*: initial;');
  for (const [k] of entries(tokens.font.size)) {
    add(`--text-${kebab(k)}: var(--mcq-font-size-${kebab(k)});`);
    add(`--text-${kebab(k)}--line-height: var(--mcq-line-height-${lineHeightFor[k] ?? 'normal'});`);
  }
  for (const [k] of entries(tokens.font.lineHeight)) {
    add(`--leading-${kebab(k)}: var(--mcq-line-height-${kebab(k)});`);
  }

  add('--spacing: var(--mcq-space-1);');
  add('--radius-*: initial;');
  for (const [k] of entries(tokens.radius))
    add(`--radius-${kebab(k)}: var(--mcq-radius-${kebab(k)});`);
  add('--shadow-*: initial;');
  for (const [k] of entries(tokens.shadow))
    add(`--shadow-${kebab(k)}: var(--mcq-shadow-${kebab(k)});`);
  add('--ease-*: initial;');
  for (const [k] of entries(tokens.motion.easing))
    add(`--ease-${kebab(k)}: var(--mcq-easing-${kebab(k)});`);
  // Breakpoints must be literal values: Tailwind compiles them into media queries.
  add('--breakpoint-*: initial;');
  for (const [k, v] of entries(tokens.breakpoint)) add(`--breakpoint-${kebab(k)}: ${v}px;`);
  add(`--container-reading: var(--mcq-size-max-reading-web);`);
  add(`--container-content: var(--mcq-size-max-content-web);`);

  lines.push('}', '');
  return lines.join('\n');
}
