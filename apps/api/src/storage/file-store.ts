import { createHmac, timingSafeEqual } from 'node:crypto';
import { createWriteStream } from 'node:fs';
import { mkdir, readFile, stat, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { presignUrl } from './sigv4';

export const FILE_STORE = Symbol('FILE_STORE');

export interface SignedPut {
  uploadUrl: string;
  /** Headers the caller must send with the PUT. */
  headers: Record<string, string>;
}

/**
 * Where uploaded files live. Cloudflare R2 in production; a folder on disk (served by this API)
 * when R2 is not configured, so staging and local development work without a bucket.
 */
export interface FileStore {
  presignPut(key: string, contentType: string, expiresSec: number): SignedPut;
  presignGet(key: string, expiresSec: number): string;
  /** Public CDN/API URL for files meant to be shown to students, or null for private files. */
  publicUrl(key: string): string | null;
  /** Server-side write (error reports). */
  write(key: string, body: string | Buffer, contentType: string): Promise<void>;
  /** Server-side read; rejects when the file is missing or larger than `maxBytes`. */
  read(key: string, maxBytes: number): Promise<Buffer>;
}

/** Keys are generated by us, but they also arrive from clients (file_url), so they are checked. */
export const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9._\-/]{0,300}$/;
export const isSafeKey = (key: string): boolean => SAFE_KEY.test(key) && !key.includes('..');

const PUBLIC_PREFIXES = ['images/', 'banners/'];
export const isPublicKey = (key: string): boolean => PUBLIC_PREFIXES.some((p) => key.startsWith(p));

// ---------------------------------------------------------------------------------- R2

export interface R2Options {
  accountId: string;
  accessKeyId: string;
  secretAccessKey: string;
  bucket: string;
  /** CDN host serving the bucket, e.g. https://cdn.example.com. Private files are never given this URL. */
  publicBaseUrl: string | undefined;
}

export class R2FileStore implements FileStore {
  private readonly host: string;

  constructor(private readonly o: R2Options) {
    this.host = `${o.accountId}.r2.cloudflarestorage.com`;
  }

  private sign(method: 'GET' | 'PUT', key: string, expiresSec: number, contentType?: string) {
    return presignUrl({
      method,
      host: this.host,
      path: `/${this.o.bucket}/${key}`,
      region: 'auto',
      accessKeyId: this.o.accessKeyId,
      secretAccessKey: this.o.secretAccessKey,
      expiresSec,
      ...(contentType ? { signedHeaders: { 'content-type': contentType } } : {}),
    });
  }

  presignPut(key: string, contentType: string, expiresSec: number): SignedPut {
    return {
      uploadUrl: this.sign('PUT', key, expiresSec, contentType),
      headers: { 'Content-Type': contentType },
    };
  }

  presignGet(key: string, expiresSec: number): string {
    return this.sign('GET', key, expiresSec);
  }

  publicUrl(key: string): string | null {
    return this.o.publicBaseUrl && isPublicKey(key)
      ? `${this.o.publicBaseUrl.replace(/\/$/, '')}/${key}`
      : null;
  }

  async write(key: string, body: string | Buffer, contentType: string): Promise<void> {
    const res = await fetch(this.sign('PUT', key, 300, contentType), {
      method: 'PUT',
      headers: { 'Content-Type': contentType },
      body: typeof body === 'string' ? body : new Uint8Array(body),
      signal: AbortSignal.timeout(60_000),
    });
    if (!res.ok) throw new Error(`R2 write failed: ${res.status}`);
  }

  async read(key: string, maxBytes: number): Promise<Buffer> {
    const res = await fetch(this.sign('GET', key, 300), { signal: AbortSignal.timeout(120_000) });
    if (!res.ok) throw new Error(`R2 read failed: ${res.status}`);
    const length = Number(res.headers.get('content-length') ?? 0);
    if (length > maxBytes) throw new Error('file too large');
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length > maxBytes) throw new Error('file too large');
    return buf;
  }
}

// ---------------------------------------------------------------------------------- local disk

export interface LocalOptions {
  dir: string;
  /** Base URL of this API, e.g. https://mcq.ellevix.com */
  apiBaseUrl: string;
  secret: string;
}

export class LocalFileStore implements FileStore {
  private readonly root: string;

  constructor(private readonly o: LocalOptions) {
    this.root = resolve(o.dir);
  }

  private sig(method: string, key: string, exp: number): string {
    return createHmac('sha256', this.o.secret)
      .update(`${method}\n${key}\n${exp}`)
      .digest('base64url');
  }

  /** Checks `?exp=&sig=` of a signed local URL. */
  verify(method: 'GET' | 'PUT', key: string, exp: number, sig: string): boolean {
    if (!Number.isFinite(exp) || exp < Math.floor(Date.now() / 1000)) return false;
    const want = Buffer.from(this.sig(method, key, exp));
    const got = Buffer.from(sig);
    return want.length === got.length && timingSafeEqual(want, got);
  }

  private url(method: 'GET' | 'PUT', key: string, expiresSec: number): string {
    const exp = Math.floor(Date.now() / 1000) + expiresSec;
    const path = key.split('/').map(encodeURIComponent).join('/');
    return `${this.o.apiBaseUrl}/v1/admin/uploads/local/${path}?exp=${exp}&sig=${this.sig(method, key, exp)}`;
  }

  presignPut(key: string, contentType: string, expiresSec: number): SignedPut {
    return {
      uploadUrl: this.url('PUT', key, expiresSec),
      headers: { 'Content-Type': contentType },
    };
  }

  presignGet(key: string, expiresSec: number): string {
    return this.url('GET', key, expiresSec);
  }

  publicUrl(key: string): string | null {
    return isPublicKey(key) ? `${this.o.apiBaseUrl}/v1/files/${key}` : null;
  }

  /** Absolute path of a key, refusing anything that would leave the upload folder. */
  path(key: string): string {
    if (!isSafeKey(key)) throw new Error('unsafe key');
    const full = resolve(join(this.root, key));
    if (!full.startsWith(this.root + sep)) throw new Error('unsafe key');
    return full;
  }

  async write(key: string, body: string | Buffer): Promise<void> {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, body);
  }

  /** Streams an upload to disk and stops (deleting the partial file) past `maxBytes`. */
  async writeStream(key: string, body: Readable, maxBytes: number): Promise<void> {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true });
    let size = 0;
    body.on('data', (chunk: Buffer) => {
      size += chunk.length;
      if (size > maxBytes) body.destroy(new Error('file too large'));
    });
    try {
      await pipeline(body, createWriteStream(file));
    } catch (err) {
      await unlink(file).catch(() => undefined);
      throw err;
    }
  }

  async read(key: string, maxBytes: number): Promise<Buffer> {
    const file = this.path(key);
    if ((await stat(file)).size > maxBytes) throw new Error('file too large');
    return readFile(file);
  }
}
